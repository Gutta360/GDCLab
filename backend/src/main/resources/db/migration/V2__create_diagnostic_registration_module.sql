CREATE TABLE gdclab.registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    registration_no VARCHAR(20) NOT NULL,
    bill_no VARCHAR(20) NOT NULL,
    patient_id BIGINT NOT NULL,
    branch_id BIGINT NOT NULL,
    registration_datetime TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    referring_doctor_id BIGINT,
    referring_lab_id BIGINT,

    patient_title_snapshot VARCHAR(20),
    patient_name_snapshot VARCHAR(101) NOT NULL,
    patient_age_snapshot SMALLINT NOT NULL,
    patient_gender_snapshot VARCHAR(10) NOT NULL,
    patient_mobile_snapshot VARCHAR(20) NOT NULL,
    patient_address_snapshot VARCHAR(255),
    branch_code_snapshot VARCHAR(20) NOT NULL,
    branch_name_snapshot VARCHAR(150) NOT NULL,
    branch_address_snapshot VARCHAR(500) NOT NULL,
    branch_phone_snapshot VARCHAR(20),
    branch_mobile_snapshot VARCHAR(20),
    referring_doctor_name_snapshot VARCHAR(150),
    referring_doctor_qualification_snapshot VARCHAR(100),
    referring_lab_name_snapshot VARCHAR(150),

    bill_amount NUMERIC(10, 2) NOT NULL,
    discount_percentage NUMERIC(5, 2) NOT NULL DEFAULT 0.00,
    discount_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    final_bill_amount NUMERIC(10, 2) NOT NULL,
    paid_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    due_amount NUMERIC(10, 2) NOT NULL,
    remarks VARCHAR(1000),
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(100),
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_registrations PRIMARY KEY (id),
    CONSTRAINT uk_registrations_registration_no UNIQUE (registration_no),
    CONSTRAINT uk_registrations_bill_no UNIQUE (bill_no),
    CONSTRAINT fk_registrations_patient FOREIGN KEY (patient_id)
        REFERENCES gdclab.patients (id) ON DELETE RESTRICT,
    CONSTRAINT fk_registrations_branch FOREIGN KEY (branch_id)
        REFERENCES gdclab.branches (id) ON DELETE RESTRICT,
    CONSTRAINT fk_registrations_referring_doctor FOREIGN KEY (referring_doctor_id)
        REFERENCES gdclab.referral_sources (id) ON DELETE RESTRICT,
    CONSTRAINT fk_registrations_referring_lab FOREIGN KEY (referring_lab_id)
        REFERENCES gdclab.referral_sources (id) ON DELETE RESTRICT,
    CONSTRAINT chk_registrations_registration_no CHECK (registration_no ~ '^REG-[0-9]{5,}$'),
    CONSTRAINT chk_registrations_bill_no CHECK (bill_no ~ '^BILL-[0-9]{5,}$'),
    CONSTRAINT chk_registrations_patient_name CHECK (NULLIF(BTRIM(patient_name_snapshot), '') IS NOT NULL),
    CONSTRAINT chk_registrations_patient_age CHECK (patient_age_snapshot BETWEEN 0 AND 120),
    CONSTRAINT chk_registrations_patient_gender CHECK (patient_gender_snapshot IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT chk_registrations_patient_mobile CHECK (patient_mobile_snapshot ~ '^[0-9]{10}$'),
    CONSTRAINT chk_registrations_branch_snapshot CHECK (
        NULLIF(BTRIM(branch_code_snapshot), '') IS NOT NULL
        AND NULLIF(BTRIM(branch_name_snapshot), '') IS NOT NULL
        AND NULLIF(BTRIM(branch_address_snapshot), '') IS NOT NULL
        AND (branch_mobile_snapshot IS NULL OR branch_mobile_snapshot ~ '^[0-9]{10}$')
    ),
    CONSTRAINT chk_registrations_doctor_snapshot CHECK (
        (referring_doctor_id IS NULL
            AND referring_doctor_name_snapshot IS NULL
            AND referring_doctor_qualification_snapshot IS NULL)
        OR (referring_doctor_id IS NOT NULL
            AND NULLIF(BTRIM(referring_doctor_name_snapshot), '') IS NOT NULL)
    ),
    CONSTRAINT chk_registrations_lab_snapshot CHECK (
        (referring_lab_id IS NULL AND referring_lab_name_snapshot IS NULL)
        OR (referring_lab_id IS NOT NULL
            AND NULLIF(BTRIM(referring_lab_name_snapshot), '') IS NOT NULL)
    ),
    CONSTRAINT chk_registrations_amounts CHECK (
        bill_amount BETWEEN 0.00 AND 99999999.99
        AND discount_amount BETWEEN 0.00 AND 99999999.99
        AND final_bill_amount BETWEEN 0.00 AND 99999999.99
        AND paid_amount BETWEEN 0.00 AND 99999999.99
        AND due_amount BETWEEN 0.00 AND 99999999.99
    ),
    CONSTRAINT chk_registrations_discount_percentage CHECK (discount_percentage BETWEEN 0.00 AND 100.00),
    CONSTRAINT chk_registrations_discount_calculation CHECK (
        discount_amount = ROUND(bill_amount * discount_percentage / 100, 2)
    ),
    CONSTRAINT chk_registrations_final_amount CHECK (final_bill_amount = bill_amount - discount_amount),
    CONSTRAINT chk_registrations_payment_balance CHECK (
        paid_amount <= final_bill_amount AND due_amount = final_bill_amount - paid_amount
    ),
    CONSTRAINT chk_registrations_status CHECK (status IN ('OPEN', 'PARTIALLY_PAID', 'PAID', 'CANCELLED')),
    CONSTRAINT chk_registrations_status_balance CHECK (
        status = 'CANCELLED'
        OR (status = 'OPEN' AND paid_amount = 0.00 AND due_amount > 0.00)
        OR (status = 'PARTIALLY_PAID' AND paid_amount > 0.00 AND due_amount > 0.00)
        OR (status = 'PAID' AND due_amount = 0.00)
    ),
    CONSTRAINT chk_registrations_version CHECK (version >= 0)
);

CREATE TABLE gdclab.registration_tests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    registration_id BIGINT NOT NULL,
    test_id BIGINT NOT NULL,
    test_name_snapshot VARCHAR(200) NOT NULL,
    category_code_snapshot VARCHAR(30) NOT NULL,
    category_name_snapshot VARCHAR(100) NOT NULL,
    test_price NUMERIC(10, 2) NOT NULL,
    discount_percentage NUMERIC(5, 2) NOT NULL DEFAULT 0.00,
    discount_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    total_amount NUMERIC(10, 2) NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'REGISTERED',
    registered_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP(6) WITH TIME ZONE,
    completed_by VARCHAR(100),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(100),
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_registration_tests PRIMARY KEY (id),
    CONSTRAINT uk_registration_tests_registration_test UNIQUE (registration_id, test_id),
    CONSTRAINT fk_registration_tests_registration FOREIGN KEY (registration_id)
        REFERENCES gdclab.registrations (id) ON DELETE RESTRICT,
    CONSTRAINT fk_registration_tests_test FOREIGN KEY (test_id)
        REFERENCES gdclab.diagnostic_tests (id) ON DELETE RESTRICT,
    CONSTRAINT chk_registration_tests_snapshot CHECK (
        NULLIF(BTRIM(test_name_snapshot), '') IS NOT NULL
        AND NULLIF(BTRIM(category_code_snapshot), '') IS NOT NULL
        AND NULLIF(BTRIM(category_name_snapshot), '') IS NOT NULL
    ),
    CONSTRAINT chk_registration_tests_amounts CHECK (
        test_price BETWEEN 0.00 AND 99999999.99
        AND discount_amount BETWEEN 0.00 AND 99999999.99
        AND total_amount BETWEEN 0.00 AND 99999999.99
    ),
    CONSTRAINT chk_registration_tests_discount_percentage CHECK (discount_percentage BETWEEN 0.00 AND 100.00),
    CONSTRAINT chk_registration_tests_discount_calculation CHECK (
        discount_amount = ROUND(test_price * discount_percentage / 100, 2)
    ),
    CONSTRAINT chk_registration_tests_total CHECK (total_amount = test_price - discount_amount),
    CONSTRAINT chk_registration_tests_display_order CHECK (display_order >= 0),
    CONSTRAINT chk_registration_tests_status CHECK (status IN ('REGISTERED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT chk_registration_tests_completion CHECK (
        (status = 'COMPLETED' AND completed_at IS NOT NULL AND completed_at >= registered_at)
        OR (status <> 'COMPLETED' AND completed_at IS NULL AND completed_by IS NULL)
    ),
    CONSTRAINT chk_registration_tests_version CHECK (version >= 0)
);

CREATE TABLE gdclab.payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payment_no VARCHAR(20) NOT NULL,
    registration_id BIGINT NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    payment_mode VARCHAR(10) NOT NULL,
    payment_datetime TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reference_no VARCHAR(100),
    remarks VARCHAR(1000),
    received_by VARCHAR(100),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(100),
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_payments PRIMARY KEY (id),
    CONSTRAINT uk_payments_payment_no UNIQUE (payment_no),
    CONSTRAINT fk_payments_registration FOREIGN KEY (registration_id)
        REFERENCES gdclab.registrations (id) ON DELETE RESTRICT,
    CONSTRAINT chk_payments_payment_no CHECK (payment_no ~ '^PAY-[0-9]{5,}$'),
    CONSTRAINT chk_payments_amount CHECK (amount > 0.00 AND amount <= 99999999.99),
    CONSTRAINT chk_payments_mode CHECK (payment_mode IN ('CASH', 'UPI', 'CARD', 'OTHER')),
    CONSTRAINT chk_payments_version CHECK (version >= 0)
);

